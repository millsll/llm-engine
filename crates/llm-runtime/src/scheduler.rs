//! 连续批处理调度器，对标 SGLang 的 Scheduler。
//!
//! 职责：
//!
//! - **准入**：按显存水位决定是否接收新请求，接不下就排队而不是 OOM。
//! - **组批**：每步动态重组 batch，已完成的序列立刻让位给新序列。
//! - **chunked prefill**：长 prompt 拆成多步前向，避免单步阻塞 decode。
//! - **抢占**：显存不足时换出或丢弃低优先级序列。
//!
//! ## 与 cache / core 的接口
//!
//! - 通过 `mem_cache::manager::CacheManager` 分配块表，把
//!   `&mut dyn KvCache` 交给前向。
//! - 通过 `llm_core` 执行批量前向，本身不接触权重张量。
//!
//! 因为不碰权重，调度器可以用 mock 执行器做完全确定性的单测：
//! 给定固定的到达顺序与显存上限，断言每一步的组批结果。
//!
